create view public.v_sotuvlar with (security_invoker = true) as
 SELECT s.id, s.chek_raqami, s.mijoz_id, s.mijoz_ismi, s.kassir_id, s.sana, s.jami_summa, s.tolov_turi,
    jsonb_array_length(s.mahsulotlar) AS mahsulotlar_soni,
    ((COALESCE(s.tolangan_summa, (0)::bigint))::numeric + COALESCE(t.tolangan, (0)::numeric)) AS jami_tolangan,
    GREATEST((((s.jami_summa - COALESCE(s.tolangan_summa, (0)::bigint)))::numeric - COALESCE(t.tolangan, (0)::numeric)), (0)::numeric) AS qarz_qoldiq,
    COALESCE(f.foyda, (0)::numeric) AS foyda,
        CASE
            WHEN ((((s.jami_summa - COALESCE(s.tolangan_summa, (0)::bigint)))::numeric - COALESCE(t.tolangan, (0)::numeric)) <= (0)::numeric) THEN 'paid'::text
            WHEN (((COALESCE(s.tolangan_summa, (0)::bigint))::numeric + COALESCE(t.tolangan, (0)::numeric)) > (0)::numeric) THEN 'partial'::text
            ELSE 'debt'::text
        END AS holat
   FROM ((sotuvlar s
     LEFT JOIN LATERAL ( SELECT sum(((x.value ->> 'summa'::text))::numeric) AS tolangan
           FROM jsonb_array_elements(s.tolovlar) x(value)) t ON (true))
     LEFT JOIN LATERAL ( SELECT sum(((((x.value ->> 'narx'::text))::numeric - COALESCE(((x.value ->> 'tannarx'::text))::numeric, (0)::numeric)) * ((x.value ->> 'soni'::text))::numeric)) AS foyda
           FROM jsonb_array_elements(s.mahsulotlar) x(value)) f ON (true));

create view public.v_taminotchilar with (security_invoker = true) as
 SELECT t.id, t.nomi, t.telefon, t.manzil, t.holat,
    jsonb_array_length(t.buyurtmalar) AS buyurtmalar_soni,
    COALESCE(b.jami_xarid, (0)::numeric) AS jami_xarid,
    GREATEST((COALESCE(b.qarz, (0)::numeric) - COALESCE(p.tolangan, (0)::numeric)), (0)::numeric) AS qarz,
    b.oxirgi_buyurtma
   FROM ((taminotchilar t
     LEFT JOIN LATERAL ( SELECT sum(((x.value ->> 'summa'::text))::numeric) AS jami_xarid,
            sum(
                CASE
                    WHEN ((x.value ->> 'tolov_holati'::text) = 'paid'::text) THEN (0)::numeric
                    WHEN (COALESCE(((x.value ->> 'qolgan_qarz'::text))::numeric, (0)::numeric) > (0)::numeric) THEN ((x.value ->> 'qolgan_qarz'::text))::numeric
                    WHEN ((x.value ->> 'tolov_holati'::text) = ANY (ARRAY['debt'::text, 'partial'::text])) THEN ((x.value ->> 'summa'::text))::numeric
                    ELSE (0)::numeric
                END) AS qarz,
            max(((x.value ->> 'sana'::text))::date) AS oxirgi_buyurtma
           FROM jsonb_array_elements(t.buyurtmalar) x(value)) b ON (true))
     LEFT JOIN LATERAL ( SELECT sum(((x.value ->> 'summa'::text))::numeric) AS tolangan
           FROM jsonb_array_elements(t.tolovlar) x(value)) p ON (true));

