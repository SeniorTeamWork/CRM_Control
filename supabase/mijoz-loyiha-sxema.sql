create view public.v_mijozlar with (security_invoker = true) as
 SELECT m.id, m.ism, m.telefon, m.hudud, m.holat, m.izoh, m.yaratilgan_at, m.yangilangan_at, m.ilova_id,
    m.malumot, m.manzil,
    COALESCE(v.xaridlar_soni, (0)::bigint) AS xaridlar_soni,
    COALESCE(v.jami_xarid, (0)::numeric) AS jami_xarid,
    COALESCE(v.qarz, (0)::numeric) AS qarz,
    v.oxirgi_xarid
   FROM (mijozlar m
     LEFT JOIN LATERAL ( SELECT count(*) AS xaridlar_soni, sum(vs.jami_summa) AS jami_xarid,
            sum(vs.qarz_qoldiq) AS qarz, max(vs.sana) AS oxirgi_xarid
           FROM v_sotuvlar vs
          WHERE (vs.mijoz_id = m.id)) v ON (true));

create view public.v_top_mahsulotlar with (security_invoker = true) as
 SELECT p.id, p.nomi, p.kategoriya, p.rasm, t.sotilgan, t.tushum
   FROM (( SELECT ((x.value ->> 'mahsulot_id'::text))::bigint AS mahsulot_id,
            sum(((x.value ->> 'soni'::text))::numeric) AS sotilgan,
            sum(COALESCE(((x.value ->> 'jami'::text))::numeric, (((x.value ->> 'narx'::text))::numeric * ((x.value ->> 'soni'::text))::numeric))) AS tushum
           FROM sotuvlar s,
            LATERAL jsonb_array_elements(s.mahsulotlar) x(value)
          WHERE ((x.value ? 'mahsulot_id'::text) AND ((x.value ->> 'mahsulot_id'::text) IS NOT NULL))
          GROUP BY ((x.value ->> 'mahsulot_id'::text))::bigint) t
     JOIN mahsulotlar p ON ((p.id = t.mahsulot_id)))
  ORDER BY t.tushum DESC;

create view public.v_dashboard with (security_invoker = true) as
 SELECT ( SELECT COALESCE(sum(sotuvlar.jami_summa), (0)::numeric) FROM sotuvlar
          WHERE (((sotuvlar.sana AT TIME ZONE 'Asia/Tashkent'::text))::date = ((now() AT TIME ZONE 'Asia/Tashkent'::text))::date)) AS bugungi_tushum,
    ( SELECT count(*) FROM sotuvlar
          WHERE (((sotuvlar.sana AT TIME ZONE 'Asia/Tashkent'::text))::date = ((now() AT TIME ZONE 'Asia/Tashkent'::text))::date)) AS bugungi_sotuvlar,
    ( SELECT COALESCE(sum(v_sotuvlar.qarz_qoldiq), (0)::numeric) FROM v_sotuvlar) AS mijozlar_qarzi,
    ( SELECT COALESCE(sum(v_taminotchilar.qarz), (0)::numeric) FROM v_taminotchilar) AS taminotchilar_qarzi,
    ( SELECT count(*) FROM mijozlar) AS mijozlar_soni,
    ( SELECT count(*) FROM mahsulotlar) AS mahsulotlar_soni,
    ( SELECT count(*) FROM v_kam_qolgan_mahsulotlar) AS kam_qolganlar,
