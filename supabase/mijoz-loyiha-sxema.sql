create view public.v_kunlik_savdo with (security_invoker = true) as
 WITH sotuv_kunlari AS (
         SELECT ((s_1.sana AT TIME ZONE 'Asia/Tashkent'::text))::date AS kun,
            sum(s_1.jami_summa) AS tushum,
            sum(COALESCE(f.foyda, (0)::numeric)) AS foyda
           FROM (sotuvlar s_1
             LEFT JOIN LATERAL ( SELECT sum(((((x.value ->> 'narx'::text))::numeric - COALESCE(((x.value ->> 'tannarx'::text))::numeric, (0)::numeric)) * ((x.value ->> 'soni'::text))::numeric)) AS foyda
                   FROM jsonb_array_elements(s_1.mahsulotlar) x(value)) f ON (true))
          GROUP BY (((s_1.sana AT TIME ZONE 'Asia/Tashkent'::text))::date)
        ), chiqim_kunlari AS (
         SELECT m.sana AS kun, sum(m.summa) AS chiqim
           FROM moliya m
          WHERE (m.turi = 'chiqim'::text)
          GROUP BY m.sana
        )
 SELECT COALESCE(s.kun, c.kun) AS kun,
    COALESCE(s.tushum, (0)::numeric) AS tushum,
    COALESCE(s.foyda, (0)::numeric) AS foyda,
    COALESCE(c.chiqim, (0)::numeric) AS chiqim
   FROM (sotuv_kunlari s
     FULL JOIN chiqim_kunlari c ON ((c.kun = s.kun)));

create view public.v_oylik_savdo with (security_invoker = true) as
 SELECT to_char((kun)::timestamp with time zone, 'YYYY-MM'::text) AS oy,
    sum(tushum) AS tushum, sum(foyda) AS foyda, sum(chiqim) AS chiqim
   FROM v_kunlik_savdo
  GROUP BY (to_char((kun)::timestamp with time zone, 'YYYY-MM'::text));

create view public.v_chiqim_kategoriyalari with (security_invoker = true) as
